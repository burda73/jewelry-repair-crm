/**
 * Шаблоны уведомлений (ТЗ п. 4, задачи 2.5–2.10).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Шаблоны — это настроечные данные: их не создают в
 * ходе работы, и очистка тестовых данных их сохраняет. Но пока список жил
 * только внутри `seed.ts`, на боевом сервере их неоткуда было взять: сид
 * создаёт демонстрационные заказы и учётные записи, и запускать его в
 * продакшне нельзя. В результате новый шаблон появлялся в коде, тесты
 * проходили, а на сервере уведомление уходило по запасному тексту — то есть
 * работало, но не так, как задумано. Один список на всех, кто его записывает,
 * убирает это расхождение.
 *
 * Тексты адресованы сотруднику или клиенту и потому отличаются: шаблон
 * `UNCLAIMED_REMINDER` — письмо клиенту («ожидает вас»), а `ORDER_UNCLAIMED` —
 * сообщение приёмщику о том, что изделие переведено в «Невостребовано».
 */

/**
 * Канал шаблона.
 *
 * Тексты для разных каналов отличаются НАМЕРЕННО, а не дублируются. Письмо
 * содержит тему и может быть длинным; сообщение в интерфейсе короткое, потому
 * что его читают урывками между клиентами; SMS ограничено примерно 70 символами,
 * и всё, что длиннее, приходит двумя сообщениями с лишней оплатой.
 */
export const TEMPLATE_CHANNEL = {
  IN_APP: 'IN_APP',
  EMAIL: 'EMAIL',
  SMS: 'SMS',
  MESSENGER: 'MESSENGER',
} as const;

export type TemplateChannel = (typeof TEMPLATE_CHANNEL)[keyof typeof TEMPLATE_CHANNEL];

/** Один шаблон уведомления. */
export interface NotificationTemplateSeed {
  /** Код из `TEMPLATE_CODE`; по нему шаблон ищется при отправке. */
  code: string;
  /**
   * Канал, которому принадлежит текст.
   *
   * Шаблон ищется по паре «код + канал»: для письма и для сообщения в интерфейсе
   * это разные записи с разным текстом.
   */
  channel: TemplateChannel;
  /**
   * Тема сообщения; подстановка — `{{переменная}}`.
   *
   * `null` у каналов, где темы нет: SMS и мессенджер доставляются одним текстом.
   * Пустая строка здесь была бы хуже `null`: она неотличима от «тему забыли
   * заполнить», и проверка «у шаблона есть тема» перестала бы что-либо ловить.
   */
  subject: string | null;
  /** Текст сообщения. */
  body: string;
}

