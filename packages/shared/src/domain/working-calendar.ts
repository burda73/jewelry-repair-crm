/**
 * Производственный календарь: государственные праздники РФ, встроенные в код.
 *
 * ЗАЧЕМ В КОДЕ, А НЕ ТОЛЬКО В БАЗЕ. Сроки в системе обещают клиенту: «5 рабочих
 * дней», «10 рабочих дней на рекламацию» (ТЗ п. 2.9), нормативы этапов (ТЗ п. 2.7).
 * Если праздник неизвестен, система поставит срок на нерабочий день — то есть
 * пообещает то, что нельзя выполнить. Дефект нашёлся фактической проверкой:
 * календарь отмечал только субботу и воскресенье, поэтому срок «5 рабочих дней
 * от 25 декабря» попадал на 1 января.
 *
 * Праздники по ТК РФ ст. 112 неизменны из года в год, поэтому их можно знать
 * всегда — в том числе за пределами периода, заполненного в базе. Переносы
 * (когда суббота объявлена рабочей или выходной перенесён) ежегодно
 * устанавливаются постановлением Правительства и заранее неизвестны, поэтому
 * в коде их нет: их вносит администратор как исключение на конкретную дату.
 *
 * Приоритет при расчёте: исключение из базы → встроенный праздник → день недели.
 * Так администратор может объявить рабочим даже государственный праздник
 * (например, если магазин работает в новогодние каникулы), и это не будет
 * перезаписано кодом.
 */

/** Праздничные дни по месяцам, кроме января (январские каникулы — отдельно). */
const FIXED_HOLIDAYS: readonly { month: number; day: number }[] = [
  { month: 2, day: 23 }, // День защитника Отечества
  { month: 3, day: 8 }, // Международный женский день
  { month: 5, day: 1 }, // Праздник Весны и Труда
  { month: 5, day: 9 }, // День Победы
  { month: 6, day: 12 }, // День России
  { month: 11, day: 4 }, // День народного единства
];

/** Первый и последний день новогодних каникул (1–8 января, ТК РФ ст. 112). */
const NEW_YEAR_FIRST_DAY = 1;
const NEW_YEAR_LAST_DAY = 8;

/**
 * Является ли дата государственным праздником РФ (без учёта переносов).
 *
 * Дата читается в UTC: ключ календаря (`YYYY-MM-DD`) — это календарная дата,
 * а не момент времени, поэтому сравнение не должно зависеть от часового пояса
 * сервера. Таймзона магазина применяется раньше — при получении ключа из даты.
 */
export function isStateHoliday(dateKey: string): boolean {
  // Формат проверяется строго, до разбора: `Number('1')` от «2027-1-1» дал бы
  // корректные месяц и день, и дата без ведущих нулей считалась бы праздником.
  // Ключ приходит из `toDateKey` в правильном виде, но полагаться на это нельзя:
  // функция экспортируется и вызывается также с пользовательским вводом.
  if (!/^\d{4}-\d{2}-\d{2}$/.test(dateKey)) return false;
  const month = Number(dateKey.slice(5, 7));
  const day = Number(dateKey.slice(8, 10));

  if (month === 1) {
    return day >= NEW_YEAR_FIRST_DAY && day <= NEW_YEAR_LAST_DAY;
  }
  return FIXED_HOLIDAYS.some((holiday) => holiday.month === month && holiday.day === day);
}

/**
 * Государственные праздники РФ в диапазоне дат включительно.
 *
 * Нужен, чтобы показать администратору предупреждение при заполнении календаря
 * на будущий год: праздники уже учтены, но переносы нужно внести вручную.
 */
export function stateHolidaysBetween(from: Date, to: Date): string[] {
  const result: string[] = [];
  const cursor = new Date(
    Date.UTC(from.getUTCFullYear(), from.getUTCMonth(), from.getUTCDate(), 0, 0, 0, 0),
  );
  const last = Date.UTC(to.getUTCFullYear(), to.getUTCMonth(), to.getUTCDate());
  while (cursor.getTime() <= last) {
    const key = cursor.toISOString().slice(0, 10);
    if (isStateHoliday(key)) result.push(key);
    cursor.setUTCDate(cursor.getUTCDate() + 1);
  }
  return result;
}
