/**
 * Тесты встроенных государственных праздников (задача 1.3.3).
 *
 * ЗАЧЕМ ЭТИ ТЕСТЫ. Календарь в базе заполняется только субботами и
 * воскресеньями, а праздники среди недели отмечались рабочими. Из-за этого
 * срок «5 рабочих дней от 25 декабря» попадал на 1 января — нерабочий день.
 * Ошибка не заметна в обычные месяцы и проявляется раз в году, поэтому её
 * закрывает тест, а не внимательность.
 *
 * Праздники берутся из ТК РФ ст. 112. Переносы (рабочая суббота) в код НЕ
 * входят: они устанавливаются постановлением Правительства на каждый год,
 * поэтому вносятся администратором как исключение и проверяются в тестах
 * календаря, а не здесь.
 */

import { describe, expect, it } from 'vitest';
import { isStateHoliday, stateHolidaysBetween } from './working-calendar.js';
import { addWorkingDays, toDateKey, type WorkingCalendar } from '../utils/dates.js';

/** Календарь без исключений: работают только встроенные правила. */
const emptyCalendar: WorkingCalendar = { overrides: new Map(), defaultHours: 8 };

describe('Праздники РФ: состав списка (ТК РФ ст. 112)', () => {
  it('нерабочие праздничные дни — все семь', () => {
    const holidays = [
      '2027-01-01', // Новогодние каникулы
      '2027-01-08', // последний день каникул
      '2027-02-23', // День защитника Отечества
      '2027-03-08', // Международный женский день
      '2027-05-01', // Праздник Весны и Труда
      '2027-05-09', // День Победы
      '2027-06-12', // День России
      '2027-11-04', // День народного единства
    ];
    for (const date of holidays) {
      expect(isStateHoliday(date), `${date} должен быть праздником`).toBe(true);
    }
  });

  it('новогодние каникулы — весь диапазон 1–8 января', () => {
    for (const day of [1, 2, 3, 4, 5, 6, 7, 8]) {
      const date = `2027-01-${String(day).padStart(2, '0')}`;
      expect(isStateHoliday(date), `${date} входит в каникулы`).toBe(true);
    }
    // 9 января — уже рабочий день (если не выходной по дню недели).
    expect(isStateHoliday('2027-01-09')).toBe(false);
  });

  it('обычные дни праздниками не считаются', () => {
    for (const date of ['2027-01-10', '2027-02-22', '2027-03-09', '2027-06-13', '2027-11-05']) {
      expect(isStateHoliday(date), `${date} — не праздник`).toBe(false);
    }
  });

  it('праздник не зависит от года', () => {
    // Одна и та же дата в разных годах — праздник, иначе список был бы привязан
    // к конкретному году и устарел бы молча.
    for (const year of [2026, 2027, 2028, 2030]) {
      expect(isStateHoliday(`${year}-03-08`), `8 марта ${year}`).toBe(true);
      expect(isStateHoliday(`${year}-11-04`), `4 ноября ${year}`).toBe(true);
    }
  });

  it('некорректный ввод не считается праздником', () => {
    for (const value of ['', '2027-1-1', '2027/01/01', 'не дата', '2027-13-45']) {
      expect(isStateHoliday(value), `«${value}» — не праздник`).toBe(false);
    }
  });
});

describe('Праздники: влияние на расчёт сроков', () => {
  it('дефект: срок не попадает на новогодние каникулы', () => {
    // Именно этот случай был сломан: 25.12.2026 (пятница) + 5 рабочих дней
    // давало 01.01.2027 — праздник. Правильный ответ — 11.01.2027:
    // 28, 29, 30, 31 декабря и 11 января (1–8 каникулы, 9–10 выходные).
    const from = new Date('2026-12-25T12:00:00Z');
    expect(toDateKey(addWorkingDays(from, 5, emptyCalendar))).toBe('2027-01-11');
  });

  it('срок не попадает ни на один праздник при длинном нормативе', () => {
    // Норматив производства COMPLEX — 15 рабочих дней.
    const from = new Date('2026-12-25T12:00:00Z');
    const due = addWorkingDays(from, 15, emptyCalendar);
    expect(isStateHoliday(toDateKey(due))).toBe(false);
  });

  it('10 рабочих дней на рекламацию через каникулы считаются верно', () => {
    // ТЗ п. 2.9. 25.12.2026 + 10 рабочих дней: декабрь 28–31 (4 дня),
    // затем 11–15 и 18 января → 18.01.2027.
    const from = new Date('2026-12-25T12:00:00Z');
    expect(toDateKey(addWorkingDays(from, 10, emptyCalendar))).toBe('2027-01-18');
  });

  it('в обычном месяце праздники не мешают', () => {
    // Понедельник 2027-09-13 + 5 рабочих дней = понедельник 2027-09-20.
    const from = new Date('2027-09-13T09:00:00Z');
    expect(toDateKey(addWorkingDays(from, 5, emptyCalendar))).toBe('2027-09-20');
  });
});

describe('Праздники: приоритет исключений из базы', () => {
  it('администратор может объявить праздник рабочим', () => {
    // Магазин работает в каникулы: исключение из базы сильнее встроенного списка.
    const calendar: WorkingCalendar = {
      overrides: new Map([['2027-01-04', { isWorkday: true, hours: 8 }]]),
      defaultHours: 8,
    };
    const from = new Date('2026-12-31T12:00:00Z');
    // 1, 2, 3 января — праздники и выходные; 4 января объявлено рабочим.
    expect(toDateKey(addWorkingDays(from, 1, calendar))).toBe('2027-01-04');
  });

  it('администратор может объявить рабочий день выходным', () => {
    // Перенос: рабочая пятница объявлена выходным днём.
    const calendar: WorkingCalendar = {
      overrides: new Map([['2027-09-17', { isWorkday: false, hours: 0 }]]),
      defaultHours: 8,
    };
    const from = new Date('2027-09-16T12:00:00Z'); // четверг
    // Пятница 17-е — выходной, значит следующий рабочий день — понедельник 20-е.
    expect(toDateKey(addWorkingDays(from, 1, calendar))).toBe('2027-09-20');
  });
});

describe('Праздники: диапазон дат', () => {
  it('находит все праздники периода', () => {
    const holidays = stateHolidaysBetween(
      new Date('2027-01-01T00:00:00Z'),
      new Date('2027-01-31T00:00:00Z'),
    );
    expect(holidays).toHaveLength(8); // 1–8 января
    expect(holidays[0]).toBe('2027-01-01');
    expect(holidays[holidays.length - 1]).toBe('2027-01-08');
  });

  it('пустой диапазон даёт пустой список', () => {
    const holidays = stateHolidaysBetween(
      new Date('2027-03-10T00:00:00Z'),
      new Date('2027-03-20T00:00:00Z'),
    );
    expect(holidays).toEqual([]);
  });

  it('период в один день включается в результат', () => {
    expect(
      stateHolidaysBetween(new Date('2027-05-09T00:00:00Z'), new Date('2027-05-09T00:00:00Z')),
    ).toEqual(['2027-05-09']);
  });

  it('находит праздники в разных годах', () => {
    const holidays = stateHolidaysBetween(
      new Date('2026-12-31T00:00:00Z'),
      new Date('2027-01-02T00:00:00Z'),
    );
    expect(holidays).toEqual(['2027-01-01', '2027-01-02']);
  });
});
