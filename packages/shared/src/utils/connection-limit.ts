/**
 * Ограничение пула соединений с базой данных.
 *
 * ## Зачем это нужно
 *
 * В продакшне база — СУЩЕСТВУЮЩИЙ сервер PostgreSQL предприятия (ответ A1),
 * общий с другими системами (включая 1С). PostgreSQL допускает `max_connections`
 * соединений на ВЕСЬ сервер, и если наше приложение займёт их все, встанут
 * другие системы. Причину при этом будут искать где угодно, кроме нашего
 * приложения: со стороны это выглядит как «лёг сервер базы».
 *
 * Prisma без `connection_limit` открывает соединения по формуле
 * «число ядер × 2 + 1» на КАЖДЫЙ процесс. Процессов три (две реплики API и
 * воркер), поэтому неограниченный пул — это реальный риск, а не теория.
 *
 * ## Почему функция живёт в общем пакете
 *
 * Клиентов Prisma в системе два: общий (`packages/db`) и собственный
 * (`PrismaService` в API). Ограничение обязано действовать в ОБОИХ, иначе
 * настройка выглядит работающей, а на деле не влияет на работающий сервис —
 * именно этот дефект и был найден (docs/15 «Дефект 55»). Общая функция — способ
 * не завести две реализации одного правила.
 *
 * Модуль намеренно не знает о Prisma: это чистая функция от строки, поэтому она
 * проверяется тестами без создания клиента и без подключения к базе.
 */

/**
 * Добавить `connection_limit` в строку подключения.
 *
 * Возвращает исходную строку, если ограничивать нечего или нечем: отсутствие
 * настройки — не повод подставлять выдуманное число, ведь у Prisma есть
 * собственное поведение по умолчанию.
 */
export function connectionLimit(url: string | undefined): string | undefined {
  if (!url) return url;

  const size = Number(process.env.DATABASE_POOL_SIZE ?? 0);
  if (!Number.isFinite(size) || size <= 0) return url;

  /*
   * Явно заданное в строке ограничение НЕ перезаписывается: администратор,
   * вписавший `connection_limit` вручную, знал, что делает, и у него может быть
   * свой расчёт бюджета. Молчаливая подмена сделала бы строку подключения
   * непредсказуемой.
   */
  if (/[?&]connection_limit=/.test(url)) return url;

  /*
   * Разделитель зависит от того, есть ли уже параметры. Наивная склейка через
   * `?` в продакшне дала бы `...?schema=public?connection_limit=10` —
   * невалидную строку, и приложение не подключилось бы к базе ВООБЩЕ.
   */
  const separator = url.includes('?') ? '&' : '?';
  return `${url}${separator}connection_limit=${size}`;
}
