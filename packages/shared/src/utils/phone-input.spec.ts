import { describe, expect, it } from 'vitest';
import { formatPhone, normalizePhone, phoneInputHint } from './dates.js';

/**
 * Ввод телефона без кода страны (требование заказчика).
 *
 * «При вводе телефона сделай возможность не вводить код страны (+7) — он должен
 * добавляться автоматически, к примеру 9333319392 сохраняется как +7 933 331-93-92».
 *
 * Нормализация это УЖЕ умела, но в интерфейсе было не видно: placeholder
 * `+7 916 123-45-67` намекал, что код обязателен, а предпросмотра не было
 * вовсе. `phoneInputHint` закрывает именно эту часть — показывает, что
 * сохранится, пока сотрудник печатает.
 */
describe('Телефон без кода страны', () => {
  it('десять цифр сохраняются с автоматическим +7', () => {
    // Тот самый пример из требования.
    expect(normalizePhone('9333319392')).toBe('+79333319392');
  });

  it('и печатаются в привычном виде', () => {
    const normalized = normalizePhone('9333319392');
    expect(normalized).not.toBeNull();
    expect(formatPhone(normalized)).toBe('+7 933 331-93-92');
  });

  it('восьмёрка в начале приводится к +7', () => {
    // Российская привычка набирать 8 — она не должна давать другой номер.
    expect(normalizePhone('89333319392')).toBe(normalizePhone('9333319392'));
  });

  it('ввод с разделителями и без них даёт один номер', () => {
    for (const input of ['933 331-93-92', '9333319392', '+7 933 331 93 92', '(933) 331-93-92']) {
      expect(normalizePhone(input), input).toBe('+79333319392');
    }
  });
});

describe('Подсказка при вводе телефона', () => {
  it('показывает готовый номер для десяти цифр', () => {
    // Сотрудник видит результат, не дожидаясь сохранения.
    expect(phoneInputHint('9333319392')).toBe('Сохранится как +7 933 331-93-92');
  });

  it('показывает ту же строку и при вводе с +7', () => {
    // Подсказка не должна зависеть от того, как именно набрали номер.
    expect(phoneInputHint('+79333319392')).toBe(phoneInputHint('9333319392'));
  });

  it('НЕ показывает подсказку для неполного номера', () => {
    /*
     * ГЛАВНАЯ проверка. Предпросмотр недописанного номера обещал бы то, чего не
     * будет: сотрудник увидел бы «сохранится как +7 933 331-93-92», набрав
     * половину, и не понял бы, почему сохранилось другое.
     */
    expect(phoneInputHint('933331')).toBeNull();
    expect(phoneInputHint('')).toBeNull();
    expect(phoneInputHint('9')).toBeNull();
  });

  it('НЕ показывает подсказку для лишних цифр', () => {
    // Двенадцать цифр — не российский номер: подсказка молчит, а проверка
    // длины сработает при сохранении.
    expect(phoneInputHint('933331939233')).toBeNull();
  });

  it('подсказка содержит сам номер, а не общую фразу', () => {
    // Общая фраза «введите номер полностью» не отвечает на вопрос сотрудника.
    const hint = phoneInputHint('9161234567');
    expect(hint).toContain('+7 916 123-45-67');
  });
});
