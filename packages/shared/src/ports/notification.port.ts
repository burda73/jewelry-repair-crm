/**
 * Порт уведомлений (задача 5.9, docs/05 §3 и §6).
 *
 * ЗАЧЕМ ПОРТ, А НЕ ПРЯМОЙ ВЫЗОВ ПОЧТЫ. Канал доставки — это то, что меняется
 * чаще всего: сегодня SMTP, завтра корпоративный шлюз, послезавтра SMS-провайдер
 * с другим API. Если доменный код знает про `nodemailer`, смена провайдера
 * превращается в правку бизнес-логики, а тесты начинают требовать живого сервера.
 *
 * ПОРТ НЕ ЗНАЕТ О БАЗЕ И ТРАНЗАКЦИЯХ (docs/05 §6.3). Он получает простые
 * структуры и возвращает простые структуры; запись в `Notification` делает
 * вызывающий код в своей транзакции. Это позволяет подменять адаптер в тестах
 * реализацией в памяти и не тащить внешнюю систему внутрь транзакции: сбой почты
 * откатил бы приём денег.
 *
 * РЕЗУЛЬТАТ ВМЕСТО ИСКЛЮЧЕНИЯ. `send` возвращает `{ ok, error }`, а не бросает
 * исключение. Разница принципиальная: недоступная почта — это штатная ситуация,
 * при которой уведомление остаётся в базе для повторной попытки. Исключение
 * заставило бы вызывающий код оборачивать каждый вызов в try/catch и однажды
 * забыть это сделать — а забытый catch означает потерянное уведомление.
 */

/** Канал доставки. Совпадает с enum схемы `NotificationChannelType`. */
export const NOTIFICATION_CHANNEL = {
  /** В приложении: внешней доставки не требует. */
  IN_APP: 'IN_APP',
  EMAIL: 'EMAIL',
  SMS: 'SMS',
  MESSENGER: 'MESSENGER',
  PUSH: 'PUSH',
} as const;

export type NotificationChannel = (typeof NOTIFICATION_CHANNEL)[keyof typeof NOTIFICATION_CHANNEL];

/** Сообщение к отправке. */
export interface OutboundMessage {
  /** Адрес или номер получателя в том виде, в каком его понимает канал. */
  recipient: string;
  subject: string | null;
  body: string;
  /** Код шаблона — для журнала и разбора: по нему видно, что именно не ушло. */
  templateCode: string;
}

/** Результат отправки. */
export interface SendResult {
  ok: boolean;
  /**
   * Причина неудачи для журнала.
   *
   * `null` при успехе. Текст, а не код: разбирать ошибку почтового сервера
   * программно нельзя — он отвечает произвольно, — а человеку в журнале нужно
   * ровно то, что ответил сервер.
   */
  error: string | null;
  /**
   * Временная ли это ошибка.
   *
   * По ней воркер решает, повторять ли отправку. Постоянную ошибку (неверный
   * адрес, отказ сервера) повторять бессмысленно: попытки закончатся одинаково, а
   * очередь будет расти.
   */
  retryable: boolean;
}

/**
 * Порт канала доставки.
 *
 * Реализации: `EmailNotificationAdapter` (SMTP), `SmsNotificationAdapter`
 * (задача 5.10), `InAppNotificationAdapter` (ничего не отправляет — канал
 * «в приложении» виден в интерфейсе).
 */
export interface NotificationPort {
  /** Канал, который обслуживает адаптер. */
  readonly channel: NotificationChannel;

  /**
   * Отправить сообщение.
   *
   * Не бросает исключений: любая ошибка возвращается в `SendResult`. Повторы
   * выполняет воркер, а не адаптер — иначе задержки перемножались бы, и
   * «три попытки» внутри каждой из трёх попыток снаружи давали бы девять.
   */
  send(message: OutboundMessage): Promise<SendResult>;
}

/**
 * Признак временной ошибки по ответу сервера.
 *
 * Вынесено в домен, потому что этим правилом пользуются все адаптеры: SMTP
 * отвечает кодами 4xx (временная) и 5xx (постоянная), HTTP-шлюзы — теми же
 * кодами в статусе. Ошибка сети и таймаут всегда временные: сервер мог быть
 * недоступен минуту.
 */
export function isRetryableByCode(code: number | string | null | undefined): boolean {
  if (code === null || code === undefined || code === '') return true;
  const numeric = typeof code === 'number' ? code : Number.parseInt(code, 10);
  if (!Number.isFinite(numeric)) return true;
  // 4xx — временная, 5xx — постоянная. Ответ вне диапазона считается временным:
  // неизвестную ошибку безопаснее повторить, чем потерять уведомление.
  if (numeric >= 500 && numeric < 600) return false;
  return true;
}

/**
 * Сколько раз повторять отправку.
 *
 * Три попытки (docs/05 §1.4): первая — сразу, две следующие — с задержкой.
 * Больше не помогает: если почта недоступна час, десять попыток не лучше трёх, а
 * очередь растёт и мешает видеть новые ошибки.
 */
export const MAX_SEND_ATTEMPTS = 3;

/**
 * Задержка перед повторной попыткой, мс.
 *
 * Экспоненциальная: 1 мин, 5 мин, 25 мин. Первая попытка не ждёт. Задержки
 * разнесены так, чтобы короткий сбой почты проходил между попытками, а не
 * упирался в них.
 */
export function retryDelayMs(attempt: number): number {
  const base = 60_000;
  const factor = 5;
  const index = Math.max(0, attempt - 1);
  return base * factor ** index;
}

/**
 * Готово ли уведомление к следующей попытке.
 *
 * `attempts` — число уже сделанных попыток. Возвращается `false`, когда попытки
 * исчерпаны: такое уведомление остаётся в `FAILED` и видно в журнале, но воркер
 * его больше не берёт — иначе очередь никогда не опустеет.
 */
export function canRetry(attempts: number): boolean {
  return attempts < MAX_SEND_ATTEMPTS;
}

/** Пора ли повторить попытку с учётом задержки. */
export function isRetryDue(attempts: number, lastAttemptAt: Date, now: Date): boolean {
  if (!canRetry(attempts)) return false;
  if (attempts === 0) return true;
  return now.getTime() - lastAttemptAt.getTime() >= retryDelayMs(attempts);
}
