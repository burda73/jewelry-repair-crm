-- Рекламации: причина отказа и отметка об отправке предупреждения (этап 6, ТЗ п. 2.9).
--
-- `rejectionReason` отдельным полем, а не в `resolution`: это разные по смыслу
-- данные (почему отказали против чем урегулировали), и урегулирование может
-- отсутствовать у отклонённой рекламации. Смешение в одной колонке сделало бы
-- выборку «сколько вернули денег» зависящей от текста.
--
-- `warningSentAt` нужна, чтобы предупреждение о сроке ушло РОВНО ОДИН РАЗ:
-- без отметки воркер слал бы его на каждом прогоне, и лента превратилась бы в шум.

-- AlterTable
ALTER TABLE "warranty_claim" ADD COLUMN     "rejectionReason" TEXT,
ADD COLUMN     "warningSentAt" TIMESTAMP(3);
