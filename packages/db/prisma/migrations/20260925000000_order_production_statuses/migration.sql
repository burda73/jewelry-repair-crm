-- Статусы этапа производства (задача 7.1, docs/16-logistics-completion.md).
--
-- Один `IN_PRODUCTION` не различал три состояния: партия принята цехом, работа
-- выдана исполнителю, работа завершена и принята менеджером. Из-за этого
-- менеджер не видел, какие заказы уже в работе, а какие ждут распределения
-- (дефект 63 в docs/15-known-issues.md).
--
-- `IN_PRODUCTION` НЕ удаляется: в нём остаются заказы, принятые цехом до этой
-- правки. Удаление значения перечисления сделало бы их нечитаемыми, а
-- PostgreSQL не умеет удалять значения enum без пересоздания типа.
--
-- PostgreSQL 12+ выполняет ADD VALUE внутри транзакции; значения здесь только
-- добавляются и в этой же транзакции не используются.

-- AlterEnum
ALTER TYPE "order_status" ADD VALUE 'ACCEPTED_BY_WORKSHOP';
ALTER TYPE "order_status" ADD VALUE 'IN_WORK';
ALTER TYPE "order_status" ADD VALUE 'WORK_COMPLETED';
