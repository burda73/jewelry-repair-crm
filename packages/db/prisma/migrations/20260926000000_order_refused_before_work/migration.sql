-- Отказ клиента до начала работ (дефект 67, docs/15-known-issues.md).
--
-- ЗАЧЕМ ОТДЕЛЬНЫЙ СТАТУС. Заказ, возвращённый из цеха БЕЗ работ, принимался
-- магазином в статус «Готов к выдаче» (`READY_FOR_PICKUP`). Оттуда отмена
-- недостижима: переход 10 «Отменить до начала работ» разрешён только из
-- `ACCEPTED`. В результате заказ, от которого отказался клиент, нельзя было ни
-- выдать (работы не выполнены, оплаты нет), ни закрыть — сценарий отказа
-- упирался в тупик, а в магазине висело изделие, которое никто не заберёт.
--
-- Решение заказчика: ввести отдельный статус «Отказ до начала работ» вместо
-- повторного использования `CANCELLED`, чтобы в отчётах и истории было видно
-- отличие «клиент отказался» от «заказ отменён сотрудником».
--
-- PostgreSQL 12+ выполняет ADD VALUE внутри транзакции; значение здесь только
-- добавляется и в этой же транзакции не используется.

-- AlterEnum
ALTER TYPE "order_status" ADD VALUE 'REFUSED_BEFORE_WORK';

-- AlterTable
-- Отметка «вернулся из цеха без работ». По ней приёмка обратной партии решает,
-- в какой статус переводить заказ: поездом «в магазин» едут и изделия после
-- выполненной работы («Готов к выдаче»), и изделия, возвращённые без работ
-- («Отказ до начала работ»), и по статусу `IN_TRANSIT_TO_STORE` они неразличимы.
ALTER TABLE "order" ADD COLUMN "returnedWithoutWorkAt" TIMESTAMP(3);

-- Индекс для области видимости магазина: отказы до начала работ — «закрытые»
-- заказы магазина, и по ним строится отчёт.
CREATE INDEX "order_returnedWithoutWorkAt_idx" ON "order"("returnedWithoutWorkAt");
