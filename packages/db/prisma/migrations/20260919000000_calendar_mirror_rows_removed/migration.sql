-- Рабочий календарь: убрать строки-зеркала и запретить дубликаты (задача 1.3.3)
--
-- ЗАЧЕМ. Государственные праздники РФ встроены в код (`isStateHoliday`), но
-- исключение из базы имеет приоритет — так администратор может объявить рабочим
-- любой день, включая праздник. Это оказалось ловушкой: `seed` заполнял таблицу
-- ЗЕРКАЛОМ правила «работают только пн–пт» — по одной строке на каждый день,
-- с `isWorkday = true` для будней. Среди этих строк были и праздники среди
-- недели, поэтому встроенный список не действовал, и срок «5 рабочих дней
-- от 25 декабря» попадал на 1 января.
--
-- ЧТО УДАЛЯЕТСЯ. Только строки, которые полностью выводятся из правила
-- «пн–пт рабочие, сб–вс выходные»:
--   * общие для сети (`storeId IS NULL`), иначе это настройка конкретного магазина;
--   * без примечания (`note IS NULL`), иначе строка содержит пометку человека;
--   * `isWorkday` совпадает с днём недели;
--   * `hours` совпадает с обычным днём (8) или выходным (0).
-- Такая строка не несёт ничего сверх правила и МЕНЯЕТ поведение только одним
-- способом: перекрывает встроенный праздник. Настройки магазинов, строки с
-- примечаниями и изменённые часы сохраняются полностью.
--
-- БЕЗОПАСНОСТЬ. Данные воспроизводимы: удаляемые строки вычисляются из даты,
-- поэтому откат не требует архива. Резервная копия справочников и календаря
-- снята перед развёртыванием (.local/, вне репозитория).
--
-- ПОЧЕМУ ЭТО НЕ ПРОТИВОРЕЧИТ РЕШЕНИЮ «НЕ УДАЛЯТЬ». Запрет удаления касался
-- справочников, на которые ссылаются документы (магазины, цеха, исполнители,
-- категории): удаление разорвало бы историю заказов. На строку календаря не
-- ссылается ни одна таблица, внешних ключей нет, а «отключить дату» смысла не
-- имеет: каждая дата либо есть в календаре, либо нет.

DELETE FROM "working_calendar"
WHERE
  "storeId" IS NULL
  AND "note" IS NULL
  AND "isWorkday" = (EXTRACT(DOW FROM "date") NOT IN (0, 6))
  AND "hours" = (CASE WHEN "isWorkday" THEN 8 ELSE 0 END);

-- Общий календарь (storeId IS NULL) ограничение "working_calendar_storeId_date_key"
-- не защищает: в PostgreSQL NULL не равен NULL, поэтому уникальность пары
-- (storeId, date) для общих строк не работает и дубликаты возможны. Это не
-- теория: комментарий в seed уже предупреждал об этом при upsert. Частичный
-- индекс закрывает дыру именно для общих строк, не затрагивая календари магазинов.
--
-- Prisma не умеет описывать частичные индексы в схеме, поэтому индекс создаётся
-- здесь. Проверено: `prisma migrate diff --from-schema-datasource ... --to-schema-datamodel ...`
-- расхождений не видит — CI-задача «Проверка миграций» остаётся зелёной.
CREATE UNIQUE INDEX "working_calendar_global_date_key"
  ON "working_calendar" ("date")
  WHERE "storeId" IS NULL;
