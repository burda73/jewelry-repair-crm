-- Уникальность шаблона уведомления по паре «код + канал» (задача 5.9).
--
-- ЗАЧЕМ. Уникальным был только `code`. Все шаблоны создавались с каналом
-- `IN_APP`, поэтому уведомление, отправляемое на почту, не находило шаблона
-- вовсе: сервис ищет по `code` И `channel`, а строки с каналом `EMAIL` не
-- существовало и не могло существовать — её заблокировал бы уникальный индекс по
-- одному коду. В результате вместо текста уходил запасной «Событие:
-- ORDER_OVERDUE», и заметить это можно было только в полученном письме: в
-- интерфейсе `IN_APP`-запись выглядит совершенно правильно.
--
-- Порядок операций важен: сначала снимается старый индекс, затем создаётся
-- новый. Обратный порядок не прошёл бы, потому что существующие строки уникальны
-- и по коду тоже — но новый индекс по паре шире, и создавать его можно было бы и
-- первым. Снимаем первым, чтобы состояние схемы было однозначным.

DROP INDEX "notification_template_code_key";

CREATE UNIQUE INDEX "notification_template_code_channel_key"
  ON "notification_template" ("code", "channel");
