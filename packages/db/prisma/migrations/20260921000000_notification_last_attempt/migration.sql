-- Момент последней попытки отправки уведомления (задача 5.9).
--
-- ЗАЧЕМ ОТДЕЛЬНОЕ ПОЛЕ. Политика повторов (docs/05 §6.3) экспоненциальная:
-- 1 минута, 5 минут, 25 минут. Чтобы её соблюсти, воркеру нужно знать, КОГДА
-- была последняя попытка. Готового поля для этого в модели не было:
--   * `sentAt` заполняется только при УСПЕХЕ — по нему нельзя понять, когда упала
--     неудачная попытка, и повтор уходил бы сразу, сводя три попытки к одной;
--   * `createdAt` не меняется, поэтому по нему вычислялась бы задержка от момента
--     СОЗДАНИЯ, а не от последней попытки: после первого сбоя повтор ждал бы
--     минуту, после второго — уже 25 минут от создания, то есть почти сразу;
--   * `updatedAt` в модели нет и не может быть добавлено задним числом без
--     изменения семантики всех записей.
--
-- ЗАЧЕМ ПОЛЕ В ИНДЕКСЕ. Воркер отбирает готовые к отправке записи по статусу и
-- каналу, а затем сравнивает `lastAttemptAt` с текущим временем. Индекс по
-- `(userId, status, lastAttemptAt)` покрывает выборку «мои непрочитанные с
-- временем попытки» для интерфейса сотрудника; основная выборка воркера
-- опирается на существующий `(status, createdAt)`.
--
-- ДАННЫЕ СУЩЕСТВУЮЩИХ ЗАПИСЕЙ НЕ МЕНЯЮТСЯ: поле пустое, и первая же попытка его
-- заполнит. Уведомления, уже отправленные до этой миграции (`SENT`), воркер не
-- трогает — он берёт только `PENDING` и `FAILED`.

ALTER TABLE "notification" ADD COLUMN "lastAttemptAt" TIMESTAMP(3);

CREATE INDEX "notification_userId_status_lastAttemptAt_idx"
  ON "notification" ("userId", "status", "lastAttemptAt");
