/**
 * Подпись клиента при выдаче заказа.
 *
 * ## Что изменилось и почему модуль остался
 *
 * Раньше подпись была УСЛОВИЕМ выдачи: переход в «Выдан» охранялся условием
 * `PICKUP_SIGNATURE`, и без файла сервер отвечал `409 PICKUP_SIGNATURE_REQUIRED`.
 * Заказчик решил, что подпись не должна блокировать выдачу, — требование снято.
 *
 * Возможность ПРИЛОЖИТЬ подпись сохранилась как необязательная отметка о
 * получении, поэтому модуль остался: он отвечает на вопрос «предлагать ли поле
 * подписи при этом переходе», и цена ошибки в нём по-прежнему высока, только
 * теперь в другую сторону.
 *
 * Обратная ошибка — снова начать ТРЕБОВАТЬ подпись — была бы хуже прежней:
 * сервер её не проверяет, значит отказ пришёл бы не от него, а от валидации в
 * форме, и сотрудник не смог бы выдать заказ, не понимая почему.
 */

/**
 * Переходы, при которых ПРЕДЛАГАЕТСЯ приложить подпись.
 *
 * Это не требование: без файла переход пройдёт. Поле показывается только там,
 * где подпись имеет смысл, — при выдаче изделия клиенту.
 */
export const SIGNATURE_OFFERED_STATUSES: readonly string[] = ['COMPLETED'];

/**
 * Показывать ли поле подписи при переходе в этот статус.
 *
 * @param to целевой статус перехода
 * @param hasSignature уже приложена ли подпись
 */
export function offersPickupSignature(to: string, hasSignature: boolean): boolean {
  return SIGNATURE_OFFERED_STATUSES.includes(to) && !hasSignature;
}

/**
 * Можно ли выполнить переход прямо сейчас.
 *
 * Подпись БОЛЬШЕ НЕ ТРЕБУЕТСЯ, поэтому файл на возможность перехода не влияет:
 * выдача не должна блокироваться из-за росчерка. Единственное, что мешает
 * отправке, — идущая загрузка: переход ушёл бы раньше, чем сохранилась подпись,
 * и файл оказался бы не привязан к заказу.
 */
export function canSubmitTransition(params: {
  to: string;
  hasSignature: boolean;
  signatureFile: File | null;
  signatureUploading: boolean;
}): boolean {
  // Пустое значение означает «сотрудник ещё не выбрал действие».
  if (params.to === '') return false;
  // Загрузка начата — ждём её завершения, иначе подпись потеряется.
  if (params.signatureUploading) return false;
  return true;
}

/**
 * Подсказка о подписи. ВСЕГДА `null`: подпись необязательна.
 *
 * Раньше здесь объяснялось, почему переход недоступен без росчерка. Теперь
 * переход доступен всегда, и подсказка, требующая подпись, вводила бы в
 * заблуждение — сотрудник искал бы, чем её приложить, вместо выдачи заказа.
 */
export function signatureHint(to: string, hasSignature: boolean): string | null {
  void to;
  void hasSignature;
  return null;
}

/**
 * Проверка файла подписи до отправки.
 *
 * На клиенте проверяется только очевидное: тип и размер. Сервер проверяет те же
 * условия повторно — клиентская проверка лишь избавляет от заведомо обречённого
 * запроса и не заменяет серверную.
 *
 * @param file выбранный файл
 * @param maxBytes предельный размер (сервер ограничивает тем же значением)
 */
export function validateSignatureFile(
  file: File,
  maxBytes: number,
): { ok: true } | { ok: false; message: string } {
  if (file.size === 0) {
    return { ok: false, message: 'Файл пуст' };
  }
  if (file.size > maxBytes) {
    const mb = Math.round(maxBytes / 1024 / 1024);
    return { ok: false, message: `Файл больше ${mb} МБ` };
  }

  /*
   * Подпись — изображение или скан. PDF допускается: подпись может прийти
   * сканом с бумажного носителя. Прочие типы отклоняются, потому что файл
   * произвольного формата в карточке заказа будет бесполезен при разбирательстве.
   */
  const allowed = ['image/', 'application/pdf'];
  if (!allowed.some((prefix) => file.type.startsWith(prefix))) {
    return { ok: false, message: 'Допустимы изображение или PDF' };
  }

  return { ok: true };
}
