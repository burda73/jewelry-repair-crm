import type { Config } from 'tailwindcss';

/**
 * Дизайн-система (docs/08-ui-ux.md §6).
 *
 * Цвета статусов задаются НЕ здесь, а словарём `STATUS_COLORS` в `@app/shared`:
 * он хранит имя тона, а классы Tailwind — в `TONES` компонента `Badge`
 * (`src/components/ui/badge.tsx`). Совпадение наборов проверяется тестом
 * `packages/shared/src/domain/status-colors-sync.spec.ts`, а опечатка в тоне не
 * компилируется благодаря типу `StatusTone`.
 *
 * Почему палитра `status.*` отсюда УДАЛЕНА. Здесь была вторая, независимая
 * палитра тех же статусов — девять hex-цветов с комментарием «соответствует
 * STATUS_COLORS». Она не использовалась НИ РАЗУ: ни одного класса `bg-status-*`
 * в разметке, ни одной ссылки на `theme.colors.status`. При этом она
 * расходилась с фактом: `dot`-индикаторы и бейджи рисуются классами вида
 * `bg-green-100`, то есть ДРУГИМИ цветами (светло-зелёный фон вместо
 * `#22c55e`). Две палитры одного смысла — это приглашение однажды поправить
 * цвет статуса в одном месте и не поправить в другом; а поскольку вторая
 * палитра мертва, её правка не дала бы вообще ничего. Мёртвое описание
 * дизайн-системы хуже отсутствующего: оно выглядит работающим.
 *
 * Если понадобится палитра для графиков и печати (там нужен именно hex, а не
 * классы), её следует вывести ИЗ `STATUS_COLORS` одним словарём, а не заводить
 * вторым.
 */
