import { fileURLToPath } from 'node:url';
import { defineConfig } from 'vitest/config';

/**
 * Тесты веб-приложения (задача 1.7.3).
 *
 * Окружение — `node`, а не `jsdom`: тестируются ЧИСТЫЕ функции работы с
 * черновиком (`readDraft`, `clearDraft`, `clearAllDraftsForUser`), которым нужен
 * только объект `localStorage`. Ставить `jsdom` и `@testing-library/react` ради
 * этого не нужно — они потянули бы зависимости в прод-сборку, а проверяемая
 * логика (разделение черновиков по сотруднику, срок годности, версия схемы) от
 * DOM не зависит.
 *
 * Компоненты в тестах не рендерятся: визуальную проверку делает человек в
 * браузере, а здесь проверяются правила, ошибка в которых приводит к утечке
 * персональных данных клиента между сотрудниками или к потере ввода.
 */
export default defineConfig({
  /*
   * Псевдоним `@/…` повторяет `tsconfig.json`: без него тест, импортирующий
   * модуль приложения, не находит его зависимости, и падает не проверяемое
   * правило, а разрешение импорта. Псевдоним был настроен только для сборки,
   * поэтому тесты до сих пор не импортировали модули с зависимостями.
   */
  resolve: {
    alias: {
      '@': fileURLToPath(new URL('./src', import.meta.url)),
    },
  },
  test: {
    environment: 'node',
    include: ['src/**/*.spec.ts', 'src/**/*.spec.tsx'],
  },
});
